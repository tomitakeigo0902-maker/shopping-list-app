// 商品名からカテゴリと単位を推定（お気に入り→履歴→辞書の順で優先）
function suggestFromName(rawName, favoritesList, historyList) {
  const name = (rawName || '').trim();
  if (!name) return null;
  const lower = name.toLowerCase();

  const fav = favoritesList.find(f => f.name === name);
  if (fav) return { category: fav.category, unit: fav.unit };

  const hist = historyList.find(h => h.itemName === name);
  if (hist) return { category: hist.category, unit: hist.unit };

  let best = null;
  for (const entry of SUGGEST_DICT) {
    if (lower.includes(entry[0].toLowerCase()) && (!best || entry[0].length > best[0].length)) {
      best = entry;
    }
  }

  // 「冷凍」を含む商品は冷凍食品カテゴリを優先（単位は基本 袋）
  if (lower.includes('冷凍')) {
    return { category: '冷凍食品', unit: best && best[1] === '冷凍食品' ? best[2] : '袋' };
  }

  return best ? { category: best[1], unit: best[2] } : null;
}

const Store = (() => {
  const KEYS = {
    items: 'sl_items',
    history: 'sl_history',
    favorites: 'sl_favorites',
    settings: 'sl_settings'
  };

  function _read(key, fallback) {
    try {
      const data = localStorage.getItem(key);
      return data ? JSON.parse(data) : fallback;
    } catch {
      return fallback;
    }
  }

  function _write(key, data) {
    try {
      localStorage.setItem(key, JSON.stringify(data));
    } catch (e) {
      if (e.name === 'QuotaExceededError') {
        alert('ストレージの容量が不足しています。履歴を削除してください。');
      }
    }
  }

  function _generateId(prefix) {
    return prefix + '_' + Date.now() + '_' + Math.random().toString(36).slice(2, 6);
  }

  function getCategoryInfo(key) {
    return CATEGORIES.find(c => c.key === key) || CATEGORIES[CATEGORIES.length - 1];
  }

  // Items
  const items = {
    getAll() {
      const all = _read(KEYS.items, []);
      const filtered = all.filter(i => !i.checked);
      if (filtered.length !== all.length) _write(KEYS.items, filtered);
      return filtered;
    },
    add(item) {
      const all = this.getAll();
      const newItem = {
        id: _generateId('item'),
        name: item.name,
        category: item.category || 'その他',
        quantity: item.quantity || 1,
        unit: item.unit || '個',
        memo: item.memo || '',
        price: item.price || '',
        url: item.url || '',
        checked: false,
        createdAt: Date.now(),
        sortOrder: all.length
      };
      all.push(newItem);
      _write(KEYS.items, all);
      return newItem;
    },
    update(id, patch) {
      const all = this.getAll();
      const idx = all.findIndex(i => i.id === id);
      if (idx === -1) return null;
      Object.assign(all[idx], patch);
      _write(KEYS.items, all);
      return all[idx];
    },
    remove(id) {
      const all = this.getAll().filter(i => i.id !== id);
      _write(KEYS.items, all);
    },
    complete(id) {
      const all = _read(KEYS.items, []);
      const idx = all.findIndex(i => i.id === id);
      if (idx === -1) return null;
      const item = all[idx];

      const histEntry = history.add({
        itemName: item.name,
        category: item.category,
        quantity: item.quantity,
        unit: item.unit,
        memo: item.memo,
        price: item.price
      });

      const cutoff = Date.now() - SIX_MONTHS_MS;
      const recentCount = history.getAll().filter(h =>
        h.itemName === item.name && h.checkedAt >= cutoff
      ).length;
      let autoFavorited = false;
      if (recentCount >= FAVORITE_THRESHOLD && !favorites.getAll().find(f => f.name === item.name)) {
        favorites.add({
          name: item.name,
          category: item.category,
          quantity: item.quantity,
          unit: item.unit,
          memo: item.memo
        });
        autoFavorited = true;
      }

      all.splice(idx, 1);
      _write(KEYS.items, all);

      return { item, historyId: histEntry.id, autoFavorited };
    },
    restore(item, historyId) {
      const all = _read(KEYS.items, []);
      if (!all.some(i => i.id === item.id)) {
        all.push(item);
        _write(KEYS.items, all);
      }
      if (historyId) history.removeById(historyId);
    },
    // Notionから取得した一覧でローカルを置き換える。
    // keepIds: まだNotionへ送れていないローカル追加分は消さずに残す
    mergeFromNotion(remote, keepIds) {
      const local = _read(KEYS.items, []);
      const keep = local.filter(i => (keepIds || []).includes(i.id));
      const merged = remote.map((r, idx) => ({
        id: r.id,
        name: r.name,
        category: r.category || 'その他',
        quantity: r.quantity || 1,
        unit: r.unit || '個',
        memo: r.memo || '',
        price: r.price === null || r.price === undefined ? '' : r.price,
        url: r.url || '',
        checked: false,
        createdAt: r.createdAt || Date.now(),
        sortOrder: idx,
        fromNotion: true
      })).concat(keep);
      _write(KEYS.items, merged);
      return merged;
    }
  };

  // History
  const history = {
    getAll() {
      return _read(KEYS.history, []);
    },
    add(entry) {
      const all = this.getAll();
      const newEntry = {
        id: _generateId('hist'),
        itemName: entry.itemName,
        category: entry.category,
        quantity: entry.quantity,
        unit: entry.unit,
        memo: entry.memo,
        price: entry.price || '',
        checkedAt: Date.now()
      };
      all.unshift(newEntry);
      // Keep max 500 history entries
      if (all.length > 500) all.length = 500;
      _write(KEYS.history, all);
      return newEntry;
    },
    removeById(id) {
      const all = this.getAll().filter(h => h.id !== id);
      _write(KEYS.history, all);
    },
    clear() {
      _write(KEYS.history, []);
    }
  };

  // Favorites
  const favorites = {
    getAll() {
      return _read(KEYS.favorites, []).sort((a, b) => b.usageCount - a.usageCount);
    },
    add(fav) {
      const all = _read(KEYS.favorites, []);
      const existing = all.find(f => f.name === fav.name);
      if (existing) {
        existing.usageCount++;
        _write(KEYS.favorites, all);
        return existing;
      }
      const newFav = {
        id: _generateId('fav'),
        name: fav.name,
        category: fav.category || 'その他',
        quantity: fav.quantity || 1,
        unit: fav.unit || '個',
        memo: fav.memo || '',
        usageCount: 1
      };
      all.push(newFav);
      _write(KEYS.favorites, all);
      return newFav;
    },
    remove(id) {
      const all = _read(KEYS.favorites, []).filter(f => f.id !== id);
      _write(KEYS.favorites, all);
    },
    update(id, patch) {
      const all = _read(KEYS.favorites, []);
      const idx = all.findIndex(f => f.id === id);
      if (idx === -1) return null;
      Object.assign(all[idx], patch);
      _write(KEYS.favorites, all);
      return all[idx];
    },
    incrementUsage(id) {
      const all = _read(KEYS.favorites, []);
      const fav = all.find(f => f.id === id);
      if (fav) {
        fav.usageCount++;
        _write(KEYS.favorites, all);
      }
    }
  };

  function suggest(name) {
    return suggestFromName(name, favorites.getAll(), history.getAll());
  }

  return { items, history, favorites, getCategoryInfo, suggest, CATEGORIES, UNITS };
})();

// 他のスクリプトから window.Store で参照できるようにする
window.Store = Store;
